    private void tampil() {
        Valid.tabelKosong(tabMode);
        try (PreparedStatement ps = koneksi.prepareStatement(
            "select set_aturan_password_smc.panjang_minimal, set_aturan_password_smc.huruf_besar, set_aturan_password_smc.huruf_kecil, set_aturan_password_smc.angka, " +
            "set_aturan_password_smc.simbol, set_aturan_password_smc.hari_peringatan from set_aturan_password_smc limit 1"
        ); ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                tabMode.addRow(new Object[] {
                    0 == rs.getInt(1) ? "-" : rs.getString(1), rs.getString(2), rs.getString(3), rs.getString(4), rs.getString(5), 0 == rs.getInt(6) ? "-" : rs.getString(6)
                });
            }
        } catch (Exception e) {
            System.out.println("Notif : " + e);
        }
    }

    private void getData() {
        int row = tbAturan.getSelectedRow();
        if (row != -1) {
            PanjangMinimal.setText("-".equals(tbAturan.getValueAt(row, 0)) ? "" : tbAturan.getValueAt(row, 0).toString());
            HurufBesar.setSelected("Yes".equals(tbAturan.getValueAt(row, 1)));
            HurufKecil.setSelected("Yes".equals(tbAturan.getValueAt(row, 2)));
            Angka.setSelected("Yes".equals(tbAturan.getValueAt(row, 3)));
            Simbol.setSelected("Yes".equals(tbAturan.getValueAt(row, 4)));
            HariPeringatan.setText("-".equals(tbAturan.getValueAt(row, 5)) ? "" : tbAturan.getValueAt(row, 5).toString());
        }
    }

    public void emptTeks() {
        PanjangMinimal.setText("");
        HurufBesar.setSelected(false);
        HurufKecil.setSelected(false);
        Angka.setSelected(false);
        Simbol.setSelected(false);
        HariPeringatan.setText("");
        tbAturan.clearSelection();
        PanjangMinimal.requestFocus();
    }
