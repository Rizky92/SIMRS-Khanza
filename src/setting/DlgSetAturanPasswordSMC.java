    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if (!PanjangMinimal.getText().isBlank() && Integer.parseInt(PanjangMinimal.getText()) > 100) {
            JOptionPane.showMessageDialog(null, "Maaf, minimal karakter password tidak boleh lebih dari 100..!!");
            PanjangMinimal.requestFocus();
        } else {
            boolean sukses = false;
            Sequel.AutoComitFalse();
            try {
                Sequel.menghapustfSmc("set_aturan_password_smc");
                sukses = Sequel.menyimpantfSmc("set_aturan_password_smc", "panjang_minimal, huruf_besar, huruf_kecil, angka, simbol, hari_peringatan",
                    PanjangMinimal.getText().isBlank() ? "0" : PanjangMinimal.getText(), HurufBesar.isSelected() ? "Yes" : "No", HurufKecil.isSelected() ? "Yes" : "No",
                    Angka.isSelected() ? "Yes" : "No", Simbol.isSelected() ? "Yes" : "No", HariPeringatan.getText().isBlank() ? "0" : HariPeringatan.getText()
                );
            } catch (Exception e) {
                System.out.println("Notif : " + e);
                sukses = false;
            }

            if (sukses) {
                Sequel.Commit();
            } else {
                Sequel.RollBack();
            }
            Sequel.AutoComitTrue();

            if (sukses) {
                tampil();
                JOptionPane.showMessageDialog(null, "Pengaturan berhasil disimpan..!!");
            } else {
                JOptionPane.showMessageDialog(null, "Pengaturan gagal disimpan..!!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_BtnSimpanActionPerformed

