    private void BtnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnHapusActionPerformed
        if (tabMode.getRowCount() == 0) {
            JOptionPane.showMessageDialog(null, "Maaf, data sudah habis...!!!!");
        } else if (JOptionPane.YES_OPTION == JOptionPane.showConfirmDialog(null, "Hapus pengaturan? Harga barang non medis akan kembali dihitung dari harga diskon ditambah PPN pembelian.", "Konfirmasi", JOptionPane.YES_NO_OPTION)) {
            if (Sequel.menghapustfSmc("set_harga_non_medis_smc")) {
                tampil();
                emptTeks();
            }
        }
    }//GEN-LAST:event_BtnHapusActionPerformed

