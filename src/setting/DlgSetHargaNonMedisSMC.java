    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if (HargaDasar.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(null, "Maaf, silahkan pilih harga dasar terlebih dahulu..!!");
            HargaDasar.requestFocus();
        } else if (PPN.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(null, "Maaf, silahkan pilih sertakan PPN pembelian terlebih dahulu..!!");
            PPN.requestFocus();
        } else {
            boolean sukses = false;
            Sequel.AutoComitFalse();
            try {
                Sequel.menghapustfSmc("set_harga_non_medis_smc");
                sukses = Sequel.menyimpantfSmc("set_harga_non_medis_smc", "hargadasar, ppn", HargaDasar.getSelectedItem().toString(), PPN.getSelectedItem().toString());
            } catch (Exception e) {
                System.out.println("Notif : " + e);
                sukses = false;
            }

            if (sukses) {
                Sequel.Commit();
            } else {
                Sequel.RollBack();
            }
            Sequel.AutoComitTrue();

            if (sukses) {
                tampil();
                JOptionPane.showMessageDialog(null, "Pengaturan berhasil disimpan..!!");
            } else {
                JOptionPane.showMessageDialog(null, "Pengaturan gagal disimpan..!!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_BtnSimpanActionPerformed

