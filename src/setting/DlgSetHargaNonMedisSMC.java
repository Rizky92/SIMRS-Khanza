    private void tampil() {
        Valid.tabelKosong(tabMode);
        try (PreparedStatement ps = koneksi.prepareStatement("select set_harga_non_medis_smc.hargadasar, set_harga_non_medis_smc.ppn from set_harga_non_medis_smc limit 1"); ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                tabMode.addRow(new Object[] {rs.getString(1), rs.getString(2)});
            }
        } catch (Exception e) {
            System.out.println("Notif : " + e);
        }
    }

    private void getData() {
        int row = tbSetting.getSelectedRow();
        if (row != -1) {
            row = tbSetting.convertRowIndexToModel(row);
            HargaDasar.setSelectedItem(tabMode.getValueAt(row, 0));
            PPN.setSelectedItem(tabMode.getValueAt(row, 1));
        }
    }

    public void emptTeks() {
        HargaDasar.setSelectedIndex(-1);
        PPN.setSelectedIndex(-1);
        tbSetting.clearSelection();
        HargaDasar.requestFocus();
    }
