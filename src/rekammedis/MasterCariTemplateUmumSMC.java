    private void tampil() {
        if (!ceksukses) {
            ceksukses = true;
            this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            LCount.setText("0");
            Template.setText("");
            Valid.tabelKosongSmc(tabMode);
            new SwingWorker<Void, Object[]>() {
                final String cari = TCari.getText().trim();

                @Override
                protected Void doInBackground() throws Exception {
                    try (PreparedStatement ps = koneksi.prepareStatement(
                        "select t.no_template, t.nama_template, ifnull(d.nm_dokter, 'Semua Dokter') as nm_dokter, t.isi_template from template_umum_smc t " +
                        "left join dokter d on t.kd_dokter = d.kd_dokter where t.menu = ? and t.field = ? and (t.kd_dokter is null or t.kd_dokter = ?) " +
                        (cari.isBlank() ? "" : "and (t.no_template like ? or t.nama_template like ? or t.isi_template like ?) ") +
                        "order by t.kd_dokter is null, t.no_template"
                    )) {
                        int p = 0;
                        ps.setString(++p, menu);
                        ps.setString(++p, field);
                        ps.setString(++p, kodeDokter);
                        if (!cari.isBlank()) {
                            ps.setString(++p, "%" + cari + "%");
                            ps.setString(++p, "%" + cari + "%");
                            ps.setString(++p, "%" + cari + "%");
                        }
                        try (ResultSet rs = ps.executeQuery()) {
                            while (rs.next()) {
                                publish(new Object[] {rs.getString("no_template"), rs.getString("nama_template"), rs.getString("nm_dokter"), rs.getString("isi_template")});
                            }
                        }
                    }

                    return null;
                }

                @Override
                protected void process(List<Object[]> chunks) {
                    chunks.forEach(tabMode::addRow);
                }

                @Override
                protected void done() {
                    try {
                        get();
                    } catch (Exception e) {
                        System.out.println("Notif : " + e);
                    }
                    tabMode.fireTableDataChanged();
                    LCount.setText(tabMode.getRowCount() + "");
                    MasterCariTemplateUmumSMC.this.setCursor(Cursor.getDefaultCursor());
                    ceksukses = false;
                }
            }.execute();
        }
    }

    private void getData() {
        if (tbTemplate.getSelectedRow() != -1) {
            Template.setText(tbTemplate.getValueAt(tbTemplate.getSelectedRow(), 3).toString());
            Template.setCaretPosition(0);
        }
    }

