    private void tampil() {
        if (!ceksukses) {
            ceksukses = true;
            this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            LCount.setText("0");
            Valid.tabelKosongSmc(tabMode);

            new SwingWorker<Void, Object[]>() {
                final String cari = TCari.getText().trim(), kunciMenu = menu.isEnabled() ? "" : getKodeMenu();
                final List<String> menuCocok = DAFTARMENU.entrySet().stream()
                    .filter(e -> e.getValue().toLowerCase().contains(cari.toLowerCase()))
                    .map(Map.Entry::getKey).collect(Collectors.toList());
                final List<String[]> fieldCocok = DAFTARFIELD.entrySet().stream()
                    .flatMap(m -> m.getValue().entrySet().stream()
                        .filter(f -> f.getValue().toLowerCase().contains(cari.toLowerCase()))
                        .map(f -> new String[] {m.getKey(), f.getKey()}))
                    .collect(Collectors.toList());

                @Override
                protected Void doInBackground() throws Exception {
                    try (PreparedStatement ps = koneksi.prepareStatement(
                        "select t.menu, t.field, t.no_template, t.nama_template, ifnull(t.kd_dokter, '') as kd_dokter, ifnull(d.nm_dokter, '') as nm_dokter, t.isi_template " +
                        "from template_umum_smc t left join dokter d on t.kd_dokter = d.kd_dokter where 1 = 1 " +
                        (kunciMenu.isBlank() ? "" : "and t.menu = ? ") +
                        (cari.isBlank() ? "" : "and (" + (menuCocok.isEmpty() ? "" : "t.menu in (" + String.join(", ", Collections.nCopies(menuCocok.size(), "?")) + ") or ") + String.join("", Collections.nCopies(fieldCocok.size(), "(t.menu = ? and t.field = ?) or ")) + "t.menu like ? or t.field like ? or t.nama_template like ? or t.kd_dokter like ? or d.nm_dokter like ? or t.isi_template like ?) ") +
                        "order by t.menu, t.field, t.no_template"
                    )) {
                        int p = 0;
                        if (!kunciMenu.isBlank()) {
                            ps.setString(++p, kunciMenu);
                        }

                        if (!cari.isBlank()) {
                            for (String kodeMenu : menuCocok) {
                                ps.setString(++p, kodeMenu);
                            }

                            for (String[] kode : fieldCocok) {
                                ps.setString(++p, kode[0]);
                                ps.setString(++p, kode[1]);
                            }

                            for (int i = 0; i < 6; i++) {
                                ps.setString(++p, "%" + cari + "%");
                            }
                        }

                        try (ResultSet rs = ps.executeQuery()) {
                            while (rs.next()) {
                                publish(new Object[] {
                                    DAFTARMENU.getOrDefault(rs.getString("menu"), rs.getString("menu")), getJudulField(rs.getString("menu"), rs.getString("field")), rs.getString("no_template"), rs.getString("nama_template"),
                                    rs.getString("kd_dokter"), rs.getString("nm_dokter"), rs.getString("isi_template"), rs.getString("menu"), rs.getString("field")
                                });
                            }
                        }
                    }

                    return null;
                }

                @Override
                protected void process(List<Object[]> chunks) {
                    chunks.forEach(tabMode::addRow);
                }

                @Override
                protected void done() {
                    try {
                        get();
                    } catch (Exception e) {
                        System.out.println("Notif : " + e);
                    }
                    tabMode.fireTableDataChanged();
                    LCount.setText(tabMode.getRowCount() + "");
                    MasterTemplateUmumSMC.this.setCursor(Cursor.getDefaultCursor());
                    ceksukses = false;
                }
            }.execute();
        }
    }

    private boolean isInputValid() {
        if (getKodeMenu().isBlank()) {
            JOptionPane.showMessageDialog(null, "Silahkan pilih menu terlebih dahulu..!!");
            menu.requestFocus();
        } else if (getKodeField().isBlank()) {
            JOptionPane.showMessageDialog(null, "Silahkan pilih field terlebih dahulu..!!");
            field.requestFocus();
        } else if (noTemplate.getText().isBlank()) {
            Valid.textKosong(noTemplate, "No. Template");
        } else if (namaTemplate.getText().isBlank()) {
            Valid.textKosong(namaTemplate, "Nama Template");
        } else if (isiTemplate.getText().isBlank()) {
            Valid.textKosong(isiTemplate, "Template");
        } else {
            return true;
        }

        return false;
    }

    private static String getJudulField(String kodeMenu, String kodeField) {
        return DAFTARFIELD.getOrDefault(kodeMenu, Collections.emptyMap()).getOrDefault(kodeField, kodeField);
    }

    private String getKodeMenu() {
        return null == menu.getSelectedKey() ? "" : menu.getSelectedKey().toString();
    }

    private String getKodeField() {
        return null == field.getSelectedKey() ? "" : field.getSelectedKey().toString();
    }

    private String getKodeDokter() {
        return kdDokter.getText().isBlank() ? null : kdDokter.getText().trim();
    }

    private String getNamaDokter() {
        if (kdDokter.getText().isBlank()) {
            return "";
        }

        return Sequel.cariIsiSmc("select dokter.nm_dokter from dokter where dokter.kd_dokter = ?", kdDokter.getText().trim());
    }

    private void autonomor() {
        if (memuat) {
            return;
        }

        if (getKodeMenu().isBlank() || getKodeField().isBlank()) {
            noTemplate.setText("");
        } else {
            noTemplate.setText(Sequel.cariIsiSmc(
                "select lpad(ifnull(max(convert(t.no_template, signed)), 0) + 1, 3, '0') from template_umum_smc t where t.menu = ? and t.field = ?",
                getKodeMenu(), getKodeField()
            ));
        }
    }

    public void emptTeks() {
        if (menu.isEnabled()) {
            menu.setSelectedIndex(0);
            field.setSelectedIndex(0);
            kdDokter.setText("");
            nmDokter.setText("");
        }

        namaTemplate.setText("");
        isiTemplate.setText("");
        autonomor();

        if (menu.isEnabled()) {
            menu.requestFocus();
        } else {
            namaTemplate.requestFocus();
        }
    }

    private void getData() {
        if (tbTemplate.getSelectedRow() != -1) {
            int row = tbTemplate.convertRowIndexToModel(tbTemplate.getSelectedRow());
            memuat = true;
            menu.setSelectedKey(tabMode.getValueAt(row, 7).toString());
            field.setSelectedKey(tabMode.getValueAt(row, 8).toString());
            memuat = false;
            noTemplate.setText(tabMode.getValueAt(row, 2).toString());
            namaTemplate.setText(tabMode.getValueAt(row, 3).toString());
            kdDokter.setText(tabMode.getValueAt(row, 4).toString());
            nmDokter.setText(tabMode.getValueAt(row, 5).toString());
            isiTemplate.setText(tabMode.getValueAt(row, 6).toString());
        }
    }

